 *   2: Fen A♥ · YOU 9♥ · Hugo 9♣ · Dara J♦    -> Dara (left bower over the ace)
 *   3: Dara A♠ · Fen Q♥ · YOU K♥ · Hugo J♠    -> you (over-ruff)
