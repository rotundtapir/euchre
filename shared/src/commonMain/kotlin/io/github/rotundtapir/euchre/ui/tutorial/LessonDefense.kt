/**
 * The pages read before the hand is dealt.
 */
private fun defensePrologue(): List<TutorialPage> = listOf(
    TutorialPage(
        title = "The other half of the game",
        body = "Half of every Euchre game is played without the trump suit you would have " +
            "chosen. When the other side makes trump, your target is simple: take three of " +
            "the five tricks. Do it and they are EUCHRED — they score nothing and your side " +
            "takes 2 points, the same as a march.\n\n" +
            "That is why passing is not a defeat. A thin hand that makes trump is a hand " +
            "you can punish.",
    ),
    TutorialPage(
        title = "Two tools",
        body = "Defending well comes down to two habits.\n\n" +
            "Do not spend a high trump under a higher one. If the maker leads a card you " +
            "cannot beat, follow with your smallest and keep the good one for a trick it " +
            "can actually take.\n\n" +
            "And watch for the OVER-RUFF: when someone trumps a suit you are also out of, " +
            "you may trump it too — with a bigger trump. Taking a trick off the maker that " +
            "way is usually where a euchre comes from.",
    ),
)

